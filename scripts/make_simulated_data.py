"""Make 1,000 clearly labelled SYNTHETIC ultrasonic readings.

The rows resemble the serial-capture CSV shape: 20 separate trials, 50
readings per trial, about 100 ms between readings, integer centimeter values,
occasional echo failures, and a servo pulse trace. Every row says SIMULATED.
These values were generated by software, not measured with an LPC1768.
No input here should be presented as a lab result.
"""

import argparse
import csv
import json
import math
import random
from datetime import datetime, timezone
from pathlib import Path


SCENARIOS = ("approach", "move_away", "stop_before_zone", "pass_by")
TRIALS_PER_SCENARIO = 5
SAMPLES_PER_TRIAL = 50


def commanded_pulse(board_time_ms: int) -> int:
    """Approximate the unchanged 1000↔2000 us servo command, not its angle."""
    phase = (board_time_ms // 100) % 40
    return 1000 + 50 * phase if phase <= 20 else 2000 - 50 * (phase - 20)


def make_rows(seed: int = 1768) -> list[dict[str, object]]:
    rng = random.Random(seed)
    rows = []
    trial_number = 0
    for scenario in SCENARIOS:
        for number in range(1, TRIALS_PER_SCENARIO + 1):
            trial_id = f"{scenario}_{number:02d}"
            # A smooth distance trajectory represents one target viewed from
            # a fixed direction. Small correlated noise mimics hand motion;
            # larger rare errors mimic messy acoustic reflections.
            speed = rng.uniform(28.0, 43.0)
            if scenario == "approach":
                start = rng.uniform(150.0, 195.0)
                actual = [max(12.0, start - speed * i / 10.0) for i in range(50)]
            elif scenario == "move_away":
                start = rng.uniform(24.0, 43.0)
                actual = [start + speed * i / 10.0 for i in range(50)]
            elif scenario == "stop_before_zone":
                start = rng.uniform(120.0, 165.0)
                stop = rng.uniform(43.0, 62.0)
                stop_time = (start - stop) / speed
                actual = [start - speed * min(i / 10.0, stop_time) for i in range(50)]
            else:
                side_gap = rng.uniform(48.0, 72.0)
                closest_time = rng.uniform(2.0, 2.9)
                actual = [math.hypot(side_gap, speed * (i / 10.0 - closest_time))
                          for i in range(50)]

            measured = []
            drift = 0.0
            for distance in actual:
                if rng.random() < 0.02:
                    measured.append(None)
                    continue
                drift = 0.7 * drift + rng.gauss(0.0, 0.7)
                error = drift + rng.gauss(0.0, 1.2)
                if rng.random() < 0.01:
                    error += rng.choice((-1, 1)) * rng.uniform(6.0, 15.0)
                floor = 35.0 if scenario in ("stop_before_zone", "pass_by") else 2.0
                measured.append(round(max(floor, min(400.0, distance + error))))

            # Trial prompts leave gaps in the hypothetical board clock and
            # sequence. Within each trial, the 50 records remain consecutive.
            first_board_ms = trial_number * 7500
            first_sequence = trial_number * 75
            for i, distance in enumerate(measured):
                board_ms = first_board_ms + i * 100
                if distance is None:
                    status = rng.choice((1, 2, 2, 2, 3, 4))
                else:
                    status = 0
                rows.append({
                    "source": "SIMULATED",
                    "trial_id": trial_id,
                    "scenario": scenario,
                    "time_ms": i * 100,
                    "distance_cm": "" if distance is None else str(distance),
                    "valid": int(distance is not None),
                    "servo_pulse_us": commanded_pulse(board_ms),
                    "status_code": status,
                    "board_seq": first_sequence + i,
                    "board_time_ms": board_ms,
                })
            trial_number += 1
    assert len(rows) == 1000
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("data/simulated_1000.csv"))
    args = parser.parse_args()
    rows = make_rows()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    metadata = {
        "source": "SIMULATED", "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "seed": 1768, "readings": 1000, "trials": 20,
        "notes": "Software-generated distances; not an LPC1768 capture",
    }
    args.output.with_suffix(".simulation.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(rows)} SIMULATED readings from 20 separate trials to {args.output}")


if __name__ == "__main__":
    main()
